POSITIONS = ("Прошлое", "Настоящее", "Будущее")


@dataclass(frozen=True)
class Card:
    slug: str
    name: str
    meaning: str


def build_deck() -> tuple[Card, ...]:
    cards = [
        Card(slug, name, meaning)
        for slug, name, meaning in MAJORS
    ]
    for suit_slug, suit_name, suit_theme in SUITS:
        for rank_slug, rank_name, rank_theme in RANKS:
            cards.append(
                Card(
                    slug=f"{rank_slug}-{suit_slug}",
                    name=f"{rank_name} {suit_name}",
                    meaning=f"{rank_theme} в сфере «{suit_theme}»",
                )
            )
    if len(cards) != 78:
        raise RuntimeError(f"deck must contain 78 cards, got {len(cards)}")
    if len({card.slug for card in cards}) != 78:
        raise RuntimeError("deck slugs must be unique")
    return tuple(cards)


DECK = build_deck()
